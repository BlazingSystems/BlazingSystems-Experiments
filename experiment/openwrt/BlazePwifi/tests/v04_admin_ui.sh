#!/bin/sh
set -eu
ROOT="$(CDPATH= cd -- "$(dirname -- "$0")/.." && pwd)"
W="$ROOT/openwrt/rootfs/www/blazepwifi"
test -f "$W/vendor/tailadmin/LICENSE"
test -f "$W/vendor/tailadmin/blaze-tailadmin.css"
test -f "$W/vendor/qrcode/qrcode.js"
test -f "$W/admin/core.js"
test -f "$W/admin/rental.js"
test -f "$W/admin/controllers.js"
grep -q 'Rental Devices' "$W/admin.html"
grep -q 'rental_device_qr' "$W/admin/rental.js"
grep -q 'rental_policy_set' "$W/admin/rental.js"
grep -q 'expected_revision' "$W/admin/rental.js"
grep -q 'Use device as is' "$W/admin/rental.js"
grep -q 'qrcode(0' "$W/admin/rental.js"
grep -q '/vendor/tailadmin/blaze-tailadmin.css' "$W/admin.html"
grep -q '/vendor/qrcode/qrcode.js' "$W/admin.html"
! grep -Eq 'https?://[^" ]+\.(css|js)' "$W/admin.html"
grep -q 'MIT License' "$W/vendor/tailadmin/LICENSE"
echo "v0.4 admin UI static checks passed"
